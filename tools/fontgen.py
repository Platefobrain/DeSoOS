# fontgen.py – the console font: kernel/drivers/DeSoConsole-Regular.ttf -> kernel/drivers/font.rs.
#
# The TTF is a pixel font: every glyph is made of 64 x 64 unit squares on an 8 x 16 cell
# (1024 units per em, ascent 768 = 12 rows above the baseline, descent 256 = 4 rows below,
# advance 512).  Each pixel is read at its centre (non-zero winding), so font.rs is the TTF
# exactly; a glyph off that grid is refused rather than rounded.
#
#   python3 tools/fontgen.py            write kernel/drivers/font.rs
#   python3 tools/fontgen.py --check    only compare with the file in the tree (exit 1 if it differs)
#
# Needs fontTools (pip install fonttools) – only for changing the font; the build uses font.rs.

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "kernel/drivers/DeSoConsole-Regular.ttf")
OUT = os.path.join(ROOT, "kernel/drivers/font.rs")

W, H, PX = 8, 16, 64
ASCENT, DESCENT, ADVANCE, UPEM = 12 * PX, 4 * PX, W * PX, 1024


def fail(msg):
    sys.exit("fontgen: " + msg)


def literal(cp):
    c = chr(cp)
    if c in "'\\":
        return "'\\" + c + "'"
    if 0x20 <= cp < 0x7F:
        return "'" + c + "'"
    return "'\\u{%x}'" % cp


def glyphs():
    try:
        from fontTools.ttLib import TTFont
        from fontTools.pens.pointInsidePen import PointInsidePen
    except ImportError:
        fail("fontTools is missing (pip install fonttools)")
    font = TTFont(TTF)
    if font["head"].unitsPerEm != UPEM or font["hhea"].ascent != ASCENT or font["hhea"].descent != -DESCENT:
        fail("not an 8x16 pixel font (units per em, ascent or descent)")
    cmap = font.getBestCmap()
    gs = font.getGlyphSet()
    glyf = font["glyf"]
    out = []
    for cp in sorted(cmap):
        name = cmap[cp]
        if font["hmtx"][name][0] != ADVANCE:
            fail("%s: advance %d, want %d" % (literal(cp), font["hmtx"][name][0], ADVANCE))
        g = glyf[name]
        if g.numberOfContours:
            coords = g.getCoordinates(glyf)[0]
            for x, y in coords:
                if x % PX or y % PX or not (0 <= x <= ADVANCE) or not (-DESCENT <= y <= ASCENT):
                    fail("%s: point (%d, %d) off the pixel grid" % (literal(cp), x, y))
        rows = []
        for r in range(H):
            y = ASCENT - PX * r - PX // 2
            bits = 0
            for c in range(W):
                pen = PointInsidePen(gs, (PX * c + PX // 2, y))
                gs[name].draw(pen)
                if pen.getResult():
                    bits |= 0x80 >> c
            rows.append(bits)
        out.append((cp, rows))
    if not any(cp == ord("?") for cp, _ in out):
        fail("no '?' (the glyph for missing characters)")
    return out


def render(gl):
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// The console font, DeSo Console: 8x16 pixels, in the style of Orbitron – wide, square letters",
        "// with cut corners.  Copyright (c) 2026 decodeSOFT / DeSo OS.",
        "//",
        "// Generated by tools/fontgen.py from kernel/drivers/DeSoConsole-Regular.ttf – do not edit;",
        "// change the TTF and run `python3 tools/fontgen.py`.  %d characters: ASCII, Latin-1, the Polish" % len(gl),
        "// letters, the euro sign, box drawing, arrows and blocks.  Each row is one byte, bit 7 = the",
        "// leftmost pixel; a character that is not here is drawn as '?'.",
        "",
        "pub const WIDTH: usize = %d;" % W,
        "pub const HEIGHT: usize = %d;" % H,
        "",
        "pub fn glyph(c: char) -> &'static [u8; HEIGHT] {",
        "    match GLYPHS.binary_search_by(|(g, _)| g.cmp(&c)) {",
        "        Ok(i) => &GLYPHS[i].1,",
        "        Err(_) => match GLYPHS.binary_search_by(|(g, _)| g.cmp(&'?')) {",
        "            Ok(i) => &GLYPHS[i].1,",
        "            Err(_) => &GLYPHS[0].1,",
        "        },",
        "    }",
        "}",
        "",
        "#[rustfmt::skip]",
        "static GLYPHS: [(char, [u8; HEIGHT]); %d] = [" % len(gl),
    ]
    for cp, rows in gl:
        lines.append("    (%s, [%s])," % (literal(cp), ", ".join("0x%02x" % b for b in rows)))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render(glyphs())
    if sys.argv[1:] == ["--check"]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            fail("kernel/drivers/font.rs differs from the TTF - run python3 tools/fontgen.py")
        print("fontgen: font.rs = the TTF")
        return
    if sys.argv[1:]:
        fail("usage: fontgen.py [--check]")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("fontgen: wrote kernel/drivers/font.rs")


if __name__ == "__main__":
    main()
